export function QuoteWidget() {
  const [index, setIndex] = useState(() => Math.floor(Math.random() * QUOTES.length));
  const [fade, setFade] = useState(true);
  const innerTimeout = useRef<ReturnType<typeof setTimeout>>(undefined);

  useEffect(() => {
    const timer = setInterval(() => {
      setFade(false);
      innerTimeout.current = setTimeout(() => {
        setIndex((prev) => (prev + 1) % QUOTES.length);
        setFade(true);
      }, 300);
    }, 3000);
    return () => { clearInterval(timer); clearTimeout(innerTimeout.current); };
  }, []);

  const q = QUOTES[index];

  return (
    <div className={`quote-widget${fade ? " quote-visible" : ""}`}>
      <Icon name="sparkles" size={14} />
      <div className="quote-content">
        <p className="quote-text">{q.text}</p>
        <span className="quote-author">— {q.author}</span>
      </div>
    </div>
  );
}
